// 3. FAST LOOKUP INDEXES (O(1) PERFORMANCE)
// ============================================================================

export const LANGUAGE_CODES: string[] = LANGUAGES_ULTRA.map(lang => lang.code);

export const DEFAULT_LANGUAGE: LanguageDefinition =
  LANGUAGES_ULTRA.find(lang => lang.default) || LANGUAGES_ULTRA[0];

export const ENABLED_LANGUAGES: LanguageDefinition[] = LANGUAGES_ULTRA.filter(
  lang => lang.enabled
);

export const RTL_LANGUAGES: LanguageDefinition[] = LANGUAGES_ULTRA.filter(
  lang => lang.rtl
);

export const LANGUAGE_MAP: Record<string, LanguageDefinition> =
  Object.fromEntries(LANGUAGES_ULTRA.map(lang => [lang.code, lang]));

export const LANGUAGE_LOCALES: Record<string, LanguageDefinition> =
  Object.fromEntries(LANGUAGES_ULTRA.map(lang => [lang.locale, lang]));

// ============================================================================
// 4. REGIONAL & LINGUISTIC GROUPS
// ============================================================================

export const AFRICAN_LANGUAGES: LanguageDefinition[] = LANGUAGES_ULTRA.filter(
  lang => lang.region === 'Africa'
);

export const EUROPEAN_LANGUAGES: LanguageDefinition[] = LANGUAGES_ULTRA.filter(
  lang => lang.region === 'Europe'
);

export const ASIAN_LANGUAGES: LanguageDefinition[] = LANGUAGES_ULTRA.filter(
  lang => lang.region === 'Asia'
);

export const AMERICAS_LANGUAGES: LanguageDefinition[] = LANGUAGES_ULTRA.filter(
  lang => lang.region === 'Americas'
);

export const OCEANIA_LANGUAGES: LanguageDefinition[] = LANGUAGES_ULTRA.filter(
  lang => lang.region === 'Oceania'
);

export const RTL_GROUP: LanguageDefinition[] = RTL_LANGUAGES;

export const LATIN_GROUP: LanguageDefinition[] = LANGUAGES_ULTRA.filter(
  lang => lang.script.includes('Latin')
);

export const CYRILLIC_GROUP: LanguageDefinition[] = LANGUAGES_ULTRA.filter(
  lang => lang.script.includes('Cyrillic')
);

export const ARABIC_GROUP: LanguageDefinition[] = LANGUAGES_ULTRA.filter(
  lang => lang.script.includes('Arabic')
);

// ============================================================================
// 5. HELPER FUNCTIONS
// ============================================================================

/**
 * Retorna a definição completa do idioma a partir do código ISO.
 */
export function getLanguage(code: string): LanguageDefinition | undefined {
  return LANGUAGE_MAP[code];
}

/**
 * Verifica se o idioma é escrito da direita para a esquerda (RTL).
 */
export function isRTL(code: string): boolean {
  return LANGUAGE_MAP[code]?.rtl ?? false;
}

/**
 * Retorna o locale completo (ex: "pt-MZ", "en-US") do código de idioma.
 */
export function getLocale(code: string): string | undefined {
  return LANGUAGE_MAP[code]?.locale;
}

/**
 * Retorna o emoji da bandeira do idioma.
 */
export function getEmoji(code: string): string | undefined {
  return LANGUAGE_MAP[code]?.emoji;
}

/**
 * Retorna a lista de provedores de IA suportados por um idioma.
 */
export function getProviders(code: string): string[] {
  return LANGUAGE_MAP[code]?.providers ?? ALL_PROVIDERS;
}

/**
 * Verifica se um código de idioma é suportado pela framework.
 */
export function isSupported(code: string): boolean {
  return code in LANGUAGE_MAP;
}

/**
 * Retorna os idiomas ordenados por prioridade definida na plataforma.
 */
export function getLanguagesByPriority(): LanguageDefinition[] {
  return [...ENABLED_LANGUAGES].sort((a, b) => a.priority - b.priority);
}


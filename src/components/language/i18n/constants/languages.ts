// ============================================================================
// 1. INTERFACE DEFINITION
// ============================================================================

export interface LanguageDefinition {
  /**
   * Código ISO de 2 letras (ou variante curta)
   * ex: "pt", "en", "ar", "zh"
   */
  code: string;

  /**
   * Locale padrão completo para formatação i18n
   * ex: "pt-MZ", "en-US", "ar-SA"
   */
  locale: string;

  /**
   * Nome nativo no próprio idioma
   * ex: "Português", "English", "العربية"
   */
  nativeName: string;

  /**
   * Nome internacional padronizado em inglês
   * ex: "Portuguese", "English", "Arabic"
   */
  englishName: string;

  /**
   * Nome do país/território principal
   */
  country: string;

  /**
   * Código ISO 3166-1 alpha-2 do país principal
   */
  countryCode: string;

  /**
   * Emoji da bandeira nacional ou regional
   */
  emoji: string;

  /**
   * Código da bandeira usado para ícones SVG (ex: flag-icons)
   */
  flag: string;

  /**
   * Indica se a escrita é Right-To-Left (Direita para Esquerda)
   */
  rtl: boolean;

  /**
   * Se o idioma está habilitado na framework
   */
  enabled: boolean;

  /**
   * Se é o idioma padrão principal da aplicação
   */
  default: boolean;

  /**
   * Provedores de IA suportados para este idioma
   */
  providers: string[];

  /**
   * Prioridade de ordenação nas UIs (1 é a maior prioridade)
   */
  priority: number;

  /**
   * Charset de codificação
   */
  charset: string;

  /**
   * Região geográfica do idioma
   */
  region: 'Africa' | 'Europe' | 'Asia' | 'Americas' | 'Oceania' | 'Global';

  /**
   * Família linguística
   */
  family: string;

  /**
   * Sistema de escrita / Alfabeto
   */
  script: string;
}

